import { IsBoolean, IsNotEmpty, IsOptional, IsString } from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class CreatePurchaseDto {
  @ApiProperty({ description: 'ID of the selected Credit Package' })
  @IsString()
  @IsNotEmpty({ message: 'Package ID is required' })
  packageId: string;

  @ApiPropertyOptional({ example: 'Festival season campaign credit purchase' })
  @IsString()
  @IsOptional()
  notes?: string;
}

export class CreatePaymentOrderDto {
  @ApiProperty({ description: 'Credit Purchase ID' })
  @IsString()
  @IsNotEmpty({ message: 'Purchase ID is required' })
  purchaseId: string;

  @ApiPropertyOptional({ default: false, description: 'Force use of local test payment simulator' })
  @IsBoolean()
  @IsOptional()
  isSimulator?: boolean;
}

export class VerifyPaymentDto {
  @ApiProperty({ description: 'Credit Purchase ID' })
  @IsString()
  @IsNotEmpty({ message: 'Purchase ID is required' })
  purchaseId: string;

  @ApiProperty({ example: 'order_M1234567890' })
  @IsString()
  @IsNotEmpty({ message: 'Razorpay Order ID is required' })
  razorpayOrderId: string;

  @ApiProperty({ example: 'pay_M1234567890' })
  @IsString()
  @IsNotEmpty({ message: 'Razorpay Payment ID is required' })
  razorpayPaymentId: string;

  @ApiPropertyOptional({ description: 'HMAC SHA256 signature generated by Razorpay' })
  @IsString()
  @IsOptional()
  razorpaySignature?: string;

  @ApiPropertyOptional({ default: false, description: 'True if executing in test simulator mode' })
  @IsBoolean()
  @IsOptional()
  isSimulator?: boolean;
}
